import fs from 'node:fs';
const read=p=>fs.readFileSync(new URL(`../${p}`,import.meta.url),'utf8');
const setup=read('components/SetupScreen.tsx');
const home=read('components/MyNetworksHome.tsx');
const app=read('components/NetworkApp.tsx');
const dataReadme=read('showcase-data/README.md');
const css=read('app/globals.css');
let pass=0,fail=0;
const ok=(name,condition)=>{if(condition){console.log(`PASS ${name}`);pass++}else{console.error(`FAIL ${name}`);fail++}};
ok('setup filters playgrounds through showcase settings',setup.includes('const playgroundKinds=')&&setup.includes('.filter(canPlayVertical)'));
ok('network selection filters playgrounds through showcase settings',home.includes('fetchShowcaseVerticalSettings')&&home.includes('const playgroundKinds=useMemo'));
ok('network selection renders filtered kinds only',home.includes('playgroundKinds.map(kind=>')&&!home.includes('network-demo-strip nx6-demo-strip">{kinds.map'));
ok('playground open action rechecks Launch Control',app.includes('if(!showcase.playground_enabled)')&&app.includes('ShowcasePlaygroundNotAvailableTxt'));
ok('creation callbacks recheck Launch Control',app.includes('ShowcaseCreationNotAvailableTxt'));
ok('first impression login is TrustWeave-wide',app.includes('ShowcaseWelcomeTitleTxt')&&app.includes('ShowcaseCommunityTitleTxt')&&app.includes('ShowcaseResidentialTitleTxt'));
ok('first setup offers focused showcase choices',setup.includes('showcase-choice-grid')&&setup.includes('qa-entry-explore-playground'));
ok('showcase data is explicitly non-importable',dataReadme.includes('do not upload these manually')||dataReadme.includes('Do **not** upload'));
ok('S2 visual foundation styles are present',css.includes('Showcase S2 — first-impression foundation')&&css.includes('.showcase-explore-grid'));
console.log(`Showcase S2 source gate: ${pass}/${pass+fail}`);
if(fail)process.exit(1);
